class relational
{
public static void main(String args[])
{
	int a=11;
	int b=17;
	System.out.println("Is a<b: "+(a<b));
	System.out.println("Is a>b: "+(a>b));
	System.out.println("Is a<=b: "+(a<=b));
	System.out.println("Is a>=b: "+(a>=b));
	System.out.println("Is a==b: "+(a==b));
	System.out.println("Is a!=b: "+(a!=b));
}
}
	
	
